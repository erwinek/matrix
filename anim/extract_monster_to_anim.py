def main():
    z = zipfile.ZipFile(ZIP)
    missing = []
    for src, dst in MAP.items():
        path = f"anim/{dst}"
        if len(path) > 63:
            raise SystemExit(f"sciezka za dluga ({len(path)}): {path}")
        out = os.path.join(ANIM, dst)
        data = z.read(src)
        with open(out, "wb") as f:
            f.write(data)
    for name in z.namelist():
        if name.endswith(".gif") and "__MACOSX" not in name and name.startswith("MONSTER"):
            if name.replace("\\", "/") not in MAP:
                missing.append(name)
    if missing:
        print("BRAK W MAP:", missing)
    print(f"OK: {len(MAP)} plikow -> {ANIM}")
    z.close()

if __name__ == "__main__":
    main()
